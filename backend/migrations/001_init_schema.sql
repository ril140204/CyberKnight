-- ── Hàm trigger cập nhật updated_at (thay cho ON UPDATE CURRENT_TIMESTAMP) ──
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ── 1. users ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name             VARCHAR(100) NOT NULL,
  last_name              VARCHAR(100) NOT NULL,
  username               VARCHAR(50)  NOT NULL,
  email                  VARCHAR(255) NOT NULL,
  password               VARCHAR(255) NOT NULL,            -- bcrypt hash
  birth_year             SMALLINT     NULL,
  level                  VARCHAR(50)  NOT NULL DEFAULT 'Rookie',
  points                 INTEGER      NOT NULL DEFAULT 0,
  avatar_url             VARCHAR(500) NULL,
  is_active              BOOLEAN      NOT NULL DEFAULT TRUE,
  role                   VARCHAR(10)  NOT NULL DEFAULT 'user'
                         CHECK (role IN ('user', 'admin')),
  failed_login_attempts  INTEGER      NOT NULL DEFAULT 0,
  locked_until           TIMESTAMPTZ  NULL,
  created_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  last_login             TIMESTAMPTZ  NULL
);

-- MySQL utf8mb4_unicode_ci không phân biệt hoa/thường → giữ nguyên hành vi bằng unique index trên LOWER()
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_lower ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower    ON users (LOWER(email));

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── 2. refresh_tokens ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS refresh_tokens (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token       VARCHAR(512) NOT NULL UNIQUE,
  token_hash  CHAR(64)     NULL,
  expires_at  TIMESTAMPTZ  NOT NULL,
  user_agent  VARCHAR(255) NULL,
  ip_address  VARCHAR(45)  NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_hash    ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user    ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires ON refresh_tokens (expires_at);

-- ── 3. password_resets ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS password_resets (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  CHAR(64)    NOT NULL UNIQUE,
  expires_at  TIMESTAMPTZ NOT NULL,
  used_at     TIMESTAMPTZ NULL,
  ip_address  VARCHAR(45) NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_password_resets_user    ON password_resets (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_password_resets_expires ON password_resets (expires_at);

-- ── 4. game_saves ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS game_saves (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  save_data   JSONB       NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
DROP TRIGGER IF EXISTS trg_game_saves_updated_at ON game_saves;
CREATE TRIGGER trg_game_saves_updated_at
  BEFORE UPDATE ON game_saves
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── 5. feedbacks ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS feedbacks (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INTEGER      NULL,
  name           VARCHAR(255) NOT NULL,
  email          VARCHAR(255) NOT NULL,
  category       VARCHAR(100) NOT NULL,
  message        TEXT         NOT NULL,
  ip             VARCHAR(45)  NULL,
  user_agent     VARCHAR(500) NULL,
  status         VARCHAR(10)  NOT NULL DEFAULT 'saved'
                 CHECK (status IN ('sent', 'saved', 'failed')),
  error_message  TEXT         NULL,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_feedbacks_created ON feedbacks (created_at);

-- ── 6. orders ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS orders (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code      VARCHAR(20)  NOT NULL UNIQUE,
  user_id         INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  package_id      VARCHAR(30)  NOT NULL,
  amount          INTEGER      NOT NULL,                    -- VND
  status          VARCHAR(10)  NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'paid', 'expired', 'cancelled', 'underpaid')),
  payment_method  VARCHAR(30)  NOT NULL DEFAULT 'bank_qr',
  expires_at      TIMESTAMPTZ  NOT NULL,
  paid_at         TIMESTAMPTZ  NULL,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_orders_user_status    ON orders (user_id, status);
CREATE INDEX IF NOT EXISTS idx_orders_status_expires ON orders (status, expires_at);
CREATE INDEX IF NOT EXISTS idx_orders_created        ON orders (created_at);

-- ── 7. payment_transactions ────────────────────────────────────
CREATE TABLE IF NOT EXISTS payment_transactions (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider          VARCHAR(20)  NOT NULL,
  provider_tx_id    VARCHAR(100) NOT NULL,
  order_id          BIGINT       NULL REFERENCES orders(id) ON DELETE SET NULL,
  amount_in         INTEGER      NOT NULL,
  content           TEXT         NULL,
  account_number    VARCHAR(50)  NULL,
  transaction_date  TIMESTAMPTZ  NULL,
  raw_payload       JSONB        NULL,
  match_status      VARCHAR(10)  NOT NULL DEFAULT 'error'
                    CHECK (match_status IN ('matched', 'no_order', 'underpaid', 'duplicate', 'error')),
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CONSTRAINT uniq_provider_tx UNIQUE (provider, provider_tx_id)
);
CREATE INDEX IF NOT EXISTS idx_tx_match_created ON payment_transactions (match_status, created_at);
CREATE INDEX IF NOT EXISTS idx_tx_order         ON payment_transactions (order_id);

-- ── 8. user_entitlements ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS user_entitlements (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  package_id  VARCHAR(30) NOT NULL,
  order_id    BIGINT      NULL REFERENCES orders(id) ON DELETE SET NULL,
  source      VARCHAR(15) NOT NULL DEFAULT 'purchase'
              CHECK (source IN ('purchase', 'admin_grant')),
  granted_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at  TIMESTAMPTZ NULL,                             -- NULL = vĩnh viễn
  CONSTRAINT uniq_user_package UNIQUE (user_id, package_id)
);

-- ── 9. admin_audit_log ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS admin_audit_log (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id        INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  action          VARCHAR(50)  NOT NULL,
  target_user_id  INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  package_id      VARCHAR(30)  NULL,
  reason          VARCHAR(255) NULL,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_audit_admin  ON admin_audit_log (admin_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_target ON admin_audit_log (target_user_id, created_at);
