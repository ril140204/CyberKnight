"""Ghép icon Lucide (ISC) + logo TikTok (Simple Icons, CC0) thành một SVG sprite tự host.

Gọi qua scripts/build-icons.sh (tự tải đúng phiên bản thư viện).
Usage: python3 -I build-icons.py <lucide icons dir> <simple-icons icons dir> <out file>
"""
import re
import sys

LUCIDE = """
shield shield-check shield-alert gamepad-2 gift door-open key-round camera clapperboard split award
smartphone users-round lock lock-keyhole lock-open mail mail-check send phone map-pin clock house
sparkles newspaper eye eye-off user-round triangle-alert circle-x x check circle-check zap crown
scroll-text log-out package star timer copy message-circle party-popper rocket arrow-left arrow-right
flame hand loader-circle lightbulb bug handshake circle-help info badge-check refresh-cw users
shopping-cart wallet credit-card user link landmark file-text globe external-link trophy
circle-dollar-sign
""".split()

lucide_dir, si_dir, out = sys.argv[1:4]
symbols = []
for name in LUCIDE:
    svg = open(f'{lucide_dir}/{name}.svg', encoding='utf-8').read()
    body = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    body = re.sub(r'\s+', ' ', body).replace(' />', '/>').strip()
    symbols.append(f'<symbol id="i-{name}" viewBox="0 0 24 24">{body}</symbol>')

tiktok = open(f'{si_dir}/tiktok.svg', encoding='utf-8').read()
path = re.search(r'<path d="([^"]+)"', tiktok).group(1)
# Logo thương hiệu là hình đặc → tự tô fill, bỏ nét (class .icon mặc định là nét)
symbols.append(f'<symbol id="i-tiktok" viewBox="0 0 24 24"><path d="{path}" fill="currentColor" stroke="none"/></symbol>')

header = ('<!-- Icons: Lucide v1.49.0 (ISC License, https://lucide.dev) · TikTok logo: Simple Icons (CC0). '
          'Generated by scripts/build-icons.sh — do not edit by hand. -->\n')
sprite = header + '<svg xmlns="http://www.w3.org/2000/svg">\n' + '\n'.join(symbols) + '\n</svg>\n'
open(out, 'w', encoding='utf-8').write(sprite)
print(len(symbols), 'symbols,', len(sprite), 'bytes')
