#!/usr/bin/env bash
# ============================================================
# CyberKnight / Sigmabloom — SSH hardening (chạy SAU khi deployer login thành công)
#
# Lưu ý: Script này có thể KHÓA BẠN KHỎI SERVER
#         BẮT BUỘC đăng nhập bằng deployer trong cửa sổ SSH MỚI
#         trước khi chạy script này.
#
# Cách dùng:
#   sudo bash deploy/finish-ssh-hardening.sh
# ============================================================

set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
  echo "LỖI: Chạy với quyền root (sudo)."
  exit 1
fi

CONF_FILE="/etc/ssh/sshd_config.d/00-hardening.conf"

echo "============================================"
echo " SSH Hardening — CyberKnight"
echo "============================================"
echo ""
echo " CẢNH BÁO: Script này sẽ:"
echo "   1. Tắt đăng nhập root (PermitRootLogin no)"
echo "   2. Tắt đăng nhập bằng mật khẩu (PasswordAuthentication no)"
echo "   3. Giới hạn 3 lần thử (MaxAuthTries 3)"
echo ""
echo " BẮT BUỘC trước khi tiếp tục:"
echo "   - Đã đăng nhập thành công bằng deployer@<IP_VPS>"
echo "   - Đã thêm SSH public key vào /home/deployer/.ssh/authorized_keys"
echo ""

# ── Check deployer SSH key (HARD STOP — must exist before running hardening) ──
check_deployer_key() {
  AUTH_KEYS="/home/deployer/.ssh/authorized_keys"

  if [ ! -f "$AUTH_KEYS" ]; then
    echo ""
    echo "============================================"
    echo "LỖI NGHIÊM TRỌNG: File SSH authorized_keys không tồn tại!"
    echo "  Path: $AUTH_KEYS"
    echo ""
    echo "Bạn chưa thêm SSH public key cho deployer. Script sẽ DỪNG LẠI"
    echo "để TRÁNH khóa bạn khỏi server."
    echo ""
    echo "Cách thêm SSH key TRƯỚC KHI chạy script này:"
    echo ""
    echo "  TRÊN MÁY LOCAL (PowerShell/WSL):"
    echo "    # Nếu chưa có key, tạo mới:"
    echo "    ssh-keygen -t ed25519 -f ~/.ssh/cyberknight_admin -N \"\" -C \"deployer-admin\""
    echo "    # Hiển thị public key để copy:"
    echo "    cat ~/.ssh/cyberknight_admin.pub"
    echo ""
    echo "  TRÊN VPS (đã đăng nhập root):"
    echo "    sudo mkdir -p /home/deployer/.ssh"
    echo "    sudo nano /home/deployer/.ssh/authorized_keys"
    echo "    # Paste public key vào, lưu (Ctrl+O, Enter, Ctrl+X)"
    echo "    sudo chown -R deployer:deployer /home/deployer/.ssh"
    echo "    sudo chmod 700 /home/deployer/.ssh"
    echo "    sudo chmod 600 /home/deployer/.ssh/authorized_keys"
    echo ""
    echo "  SAU ĐÓ, TEST từ cửa sổ SSH MỚI:"
    echo "    ssh -i ~/.ssh/cyberknight_admin deployer@<IP_VPS> \"whoami\""
    echo "    # Phải in: deployer"
    echo ""
    echo "  CHỈ SAU KHI deployer đăng nhập THÀNH CÔNG, chạy lại script này."
    echo "============================================"
    exit 1
  fi

  # Kiểm tra file không rỗng
  KEY_LINE_COUNT=$(grep -cE '^(ssh-rsa|ssh-ed25519|ecdsa-sha2)' "$AUTH_KEYS" 2>/dev/null || echo 0)
  if [ "$KEY_LINE_COUNT" -eq 0 ]; then
    echo ""
    echo "============================================"
    echo "LỖI: $AUTH_KEYS tồn tại nhưng KHÔNG có SSH public key hợp lệ!"
    echo ""
    echo "File phải chứa ít nhất 1 dòng bắt đầu bằng:"
    echo "  ssh-rsa, ssh-ed25519, hoặc ecdsa-sha2"
    echo ""
    echo "Cách thêm key đúng:"
    echo "  TRÊN MÁY LOCAL:"
    echo "    cat ~/.ssh/cyberknight_admin.pub"
    echo "  TRÊN VPS (đã đăng nhập root):"
    echo "    sudo nano /home/deployer/.ssh/authorized_keys"
    echo "    # Paste toàn bộ nội dung .pub (1 dòng dài)"
    echo "    sudo chown deployer:deployer /home/deployer/.ssh/authorized_keys"
    echo "    sudo chmod 600 /home/deployer/.ssh/authorized_keys"
    echo ""
    echo "CHỈ SAU KHI có key hợp lệ, chạy lại script này."
    echo "============================================"
    exit 1
  fi

  echo "[OK] Deployer SSH key hợp lệ: $KEY_LINE_COUNT key(s) trong authorized_keys"
}

# Chạy kiểm tra BẮT BUỘC trước khi làm bất cứ điều gì
check_deployer_key

echo ""
echo "--- Kiểm tra deployer SSH access ---"
echo "[OK] Bước kiểm tra key đã qua — deployer SSH key đã xác nhận."

# ── Write SSH hardening config ──────────────────────────────
echo ""
echo "--- Ghi file cấu hình SSH hardening ---"
cat > "$CONF_FILE" << 'SSHEOF'
# SSH Hardening — CyberKnight / Sigmabloom
# Generated by deploy/finish-ssh-hardening.sh
PermitRootLogin no
PasswordAuthentication no
KbdInteractiveAuthentication no
MaxAuthTries 3
X11Forwarding no
SSHEOF

echo "[OK] Đã ghi: $CONF_FILE"
cat "$CONF_FILE"

# ── Test sshd config ────────────────────────────────────────
echo ""
echo "--- Kiểm tra cú pháp sshd ---"
if sshd -t 2>&1; then
  echo "[OK] Cấu hình sshd hợp lệ."
else
  echo "LỖI: Cấu hình sshd không hợp lệ."
  echo "Rollback:"
  echo "  sudo rm -f $CONF_FILE"
  echo "  sudo systemctl reload ssh"
  rm -f "$CONF_FILE"
  exit 1
fi

# ── Reload sshd ─────────────────────────────────────────────
echo ""
echo "--- Reload sshd ---"
systemctl reload ssh
echo "[OK] sshd đã reload."

# ── Verify ─────────────────────────────────────────────────
echo ""
echo "--- Xác nhận cấu hình đã áp dụng ---"
sshd -T | grep -E 'passwordauthentication|permitrootlogin|maxauthtries|x11forwarding'

echo ""
echo "============================================"
echo " SSH HARDENING HOÀN TẤT!"
echo "============================================"
echo ""
echo " Kiểm tra:"
echo "   1. Đăng nhập root bằng password → BỊ CHẶN ✓"
echo "   2. Đăng nhập deployer bằng password → BỊ CHẶN ✓"
echo "   3. Đăng nhập deployer bằng SSH key → ĐƯỢC PHÉP ✓"
echo ""
echo " Nếu bị khóa khỏi server: dùng console/VNC của provider"
echo " để sửa $CONF_FILE hoặc xóa nó."
echo "============================================"
